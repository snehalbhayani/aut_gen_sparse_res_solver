"""MATLAB/Octave code generation for a reduced template.

The generated solver.m keeps the calling convention of the Maple-generated
solvers (so test_solver.m / benchmark_solver.m keep working):

    PEPsolutions = solver(data)      % one row per solution
    columns: [a_h, the other unknowns in increasing index, lambda]
"""
import json

import sympy
from sympy.printing.octave import octave_code

from .numeric import SolverLayout


def _vec(xs):
    return '[' + ' '.join(str(x) for x in xs) + ']'


def matlab_solver(problem, T, funcname='solver', cse=True):
    L = SolverLayout(problem, T)
    n, h = problem.n, T.h
    lines = [f'function PEPsolutions = {funcname}(data)',
             f'% Sparse resultant solver for {problem.name}, generated by symgen.',
             f'% Template: {L.nG} x {L.nG} elimination, {L.nE} x {L.nE} eigenvalue problem,',
             f'% hidden variable a{h + 1}.  Columns of PEPsolutions: '
             + ', '.join(['a%d' % (h + 1)] + ['a%d' % (i + 1) for i in range(n) if i != h] + ['lambda']) + '.',
             'data = data(:);']
    # data symbols -> data(i)
    sub = {p: sympy.Symbol(f'data({i + 1})') for i, p in enumerate(problem.params)}
    exprs = [problem.coeffs[c].xreplace(sub) for c in L.used_coeffs]
    # intermediate coefficients (only those actually needed), computed first
    needed = set().union(*[e.free_symbols for e in exprs]) if exprs else set()
    aux = []
    for s, e in reversed(problem.aux):
        if s in needed:
            aux.append((s, e.xreplace(sub)))
            needed |= e.free_symbols
    aux.reverse()
    if cse:
        reps, red = sympy.cse([e for _, e in aux] + exprs, symbols=sympy.numbered_symbols('s'),
                              optimizations='basic')
        aux = [(s, e) for (s, _), e in zip(aux, red[:len(aux)])]
        exprs = red[len(aux):]
        stmts = list(reps) + aux
    else:
        stmts = aux
    # emit definitions in dependency order (CSE temporaries and aux refer to each other)
    defined = {s for s, _ in stmts}
    done, pending = set(), list(stmts)
    while pending:
        rest = []
        for s, e in pending:
            if (e.free_symbols & defined) <= done:
                lines.append(f'{s} = {octave_code(e)};')
                done.add(s)
            else:
                rest.append((s, e))
        if len(rest) == len(pending):
            raise RuntimeError('cyclic coefficient definitions')
        pending = rest
    lines.append(f'k = zeros({len(exprs)},1);')
    for i, e in enumerate(exprs):
        lines.append(f'k({i + 1}) = {octave_code(e)};')
    cpos = {c: i + 1 for i, c in enumerate(L.used_coeffs)}

    def fill(name, rows, cols, entries):
        lin = [i + j * rows + 1 for i, j, _ in entries]
        ids = [cpos[c] for _, _, c in entries]
        return [f'{name} = zeros({rows},{cols});', f'{name}({_vec(lin)}) = k({_vec(ids)});']

    lines += fill('A2', L.nG, L.nG, L.A2)
    lines += fill('A1', L.nG, L.nE, L.A1)
    lines.append('K = A2 \\ A1;')
    lines.append(f'X = zeros({L.nE});')
    if L.X_unit:
        lines.append(f'X({_vec([i + j * L.nE + 1 for i, j in L.X_unit])}) = 1;')
    if L.X_from_K:
        lines.append(f'X({_vec([i + 1 for i, _ in L.X_from_K])},:) = -K({_vec([g + 1 for _, g in L.X_from_K])},:);')
    lines += ['[V, D] = eig(X);',
              'lam = diag(D);',
              'good = isfinite(lam);',
              'lam = lam(good); V = V(:, good);',
              'W = [V; -K*V];',
              'ns = numel(lam); nw = size(W,1); idx = (0:ns-1)*nw;',
              f'sols = zeros(ns, {n});',
              f'sols(:, {h + 1}) = lam;']
    for i, pairs in L.recovery.items():
        P = [p + 1 for p, _ in pairs]
        Q = [q + 1 for _, q in pairs]
        lines += [f'P = {_vec(P)}; Q = {_vec(Q)};',
                  '[~, b] = max(abs(W(P, :)), [], 1);',
                  f'sols(:, {i + 1}) = (W(Q(b) + idx) ./ W(P(b) + idx)).\';']
    order = [h + 1] + [i + 1 for i in range(n) if i != h]
    lines.append(f'PEPsolutions = [sols(:, {_vec(order)}), lam];')
    lines.append('end')
    return '\n'.join(lines) + '\n'


def template_json(problem, T):
    return json.dumps({
        'problem': problem.name,
        'hidden_var': T.h + 1,
        'eigen_basis': [list(e) for e in T.E],
        'eliminated_basis': [list(g) for g in T.G],
        'rows': [{'eq': k + 1, 'multiplier': list(t)} for k, t in T.top],
        'info': {k: (list(v) if isinstance(v, tuple) else v) for k, v in T.info.items()},
    }, indent=1)
